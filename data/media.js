/**
 * Get media item by ID
 * @param {string} id - The media ID
 * @returns {object|null} - Media object or null if not found
 */
function getMediaById(id) {
  return MEDIA_DATA[id] || null;
}

/**
 * Get all media items
 * @returns {object} - All media data
 */
function getAllMedia() {
  return MEDIA_DATA;
}

/**
 * Get media items by chapter
 * @param {number} chapter - Chapter number
 * @returns {array} - Array of media objects
 */
function getMediaByChapter(chapter) {
  return Object.entries(MEDIA_DATA)
    .filter(([id, media]) => media.chapter === chapter)
    .map(([id, media]) => ({ id, ...media }));
}

/**
 * Get media items by type
 * @param {string} type - Media type (photo, video, audio, link, pdf)
 * @returns {array} - Array of media objects
 */
function getMediaByType(type) {
  return Object.entries(MEDIA_DATA)
    .filter(([id, media]) => media.type === type)
    .map(([id, media]) => ({ id, ...media }));
}

